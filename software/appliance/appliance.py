class ApplianceError(ValueError):
    """The requested appliance state is invalid or unsafe to apply."""


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds")


def load_manifest() -> dict:
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


def root_path(root: Path, absolute: str) -> Path:
    if not absolute.startswith("/"):
        raise ApplianceError(f"appliance path must be absolute: {absolute}")
    return root / absolute.removeprefix("/")


